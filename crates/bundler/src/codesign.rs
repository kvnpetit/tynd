//! Cross-host codesign dispatcher built on `apple-codesign` (indygreg) — Linux
//! CI can produce signed + notarized Mac builds without a Mac runner. Windows
//! Authenticode happens inline during `bundle` because no production-ready
//! pure-Rust replacement for `signtool` exists yet.
//!
//! Actions: `sign` (embed signature in place) or `notarize` (sign + submit to
//! Apple's notary service + staple the ticket). Both idempotent.

use std::{fmt, io::Read as _, path::Path, time::Duration};

use anyhow::{Context, Result};
use app_store_connect::notary_api::SubmissionResponseStatus;
use apple_codesign::{
    cryptography::{parse_pfx_data, PrivateKey},
    notarization::{NotarizationUpload, Notarizer},
    stapling::Stapler,
    CodeSignatureFlags, SettingsScope, SigningSettings, UnifiedSigner,
};
use error_stack::{Report, ResultExt as _};
use miette::Diagnostic;
use thiserror::Error;
use tracing::{info, warn};
use tynd_bundle_contract::{
    CodesignAction as Action, CodesignConfig, CodesignIdentity as Identity,
};

/// `error-stack` context markers for the helper chains. Final reports are
/// rendered into the `cause` / `status` fields of `CodesignError` at the
/// boundary so user-facing diagnostics keep their code/url/help affordances
/// while gaining the structured attachments (P12 path, target path, API key
/// path, submission id) that `format!("{e:#}")` would otherwise flatten.
#[derive(Debug)]
pub(crate) enum CodesignContext {
    LoadP12,
    LoadApiKey,
    SignArtifact,
    NotarizeSubmit,
    StapleArtifact,
}

impl fmt::Display for CodesignContext {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::LoadP12 => f.write_str("load PKCS#12 identity"),
            Self::LoadApiKey => f.write_str("load App Store Connect API key"),
            Self::SignArtifact => f.write_str("sign artifact in place"),
            Self::NotarizeSubmit => f.write_str("submit artifact to Apple notary service"),
            Self::StapleArtifact => f.write_str("staple notarization ticket"),
        }
    }
}

impl std::error::Error for CodesignContext {}

/// 15 minutes covers most real Apple submissions; past that we surface the
/// upload ID so the user can resume manually.
const NOTARIZE_WAIT: Duration = Duration::from_mins(15);
const MAX_P12_BYTES: u64 = 16 * 1024 * 1024;
const MAX_ENTITLEMENTS_BYTES: u64 = 1024 * 1024;
const MAX_API_KEY_BYTES: u64 = 1024 * 1024;

/// `Clone` is required so `main.rs` can hand a value to `miette::Report::new`
/// after a downcast. Sources are rendered to `String` because `anyhow::Error`
/// is not `Clone`.
#[derive(Debug, Clone, Error, Diagnostic)]
pub(crate) enum CodesignError {
    #[error("notarization requested but `notarization` block is missing")]
    #[diagnostic(
        code(tynd::codesign::missing_apple_credentials),
        url("https://kvnpetit.github.io/tynd/docs/v1.0/guides/code-signing"),
        help(
            "set `notarization.api_key_path` in your codesign config — point it at a JSON file \
             produced by `rcodesign encode-app-store-connect-api-key`."
        )
    )]
    MissingAppleCredentials,

    #[error("failed to load App Store Connect API key {path}: {cause}")]
    #[diagnostic(
        code(tynd::codesign::api_key_load),
        url("https://kvnpetit.github.io/tynd/docs/v1.0/guides/code-signing"),
        help(
            "verify the file exists and was generated by `rcodesign \
             encode-app-store-connect-api-key`. It must contain `key_id`, `issuer_id`, and the \
             .p8 PEM body."
        )
    )]
    ApiKeyLoad { path: String, cause: String },

    #[error("identity.p12: env var {env_var} not set or empty")]
    #[diagnostic(
        code(tynd::codesign::missing_password_env),
        url("https://kvnpetit.github.io/tynd/docs/v1.0/guides/code-signing"),
        help(
            "export the P12 password before running, e.g. `export TYND_P12_PASSWORD=...`. The \
             variable name comes from `identity.password_env` in your config."
        )
    )]
    MissingPasswordEnv { env_var: String },

    #[error("failed to read P12 file {path}: {cause}")]
    #[diagnostic(
        code(tynd::codesign::p12_read),
        url("https://kvnpetit.github.io/tynd/docs/v1.0/guides/code-signing"),
        help(
            "the path in `identity.path` must point to a readable PKCS#12 file. Check permissions \
             and the absolute path."
        )
    )]
    P12Read { path: String, cause: String },

    /// `apple-codesign` collapses wrong-password / corrupt / non-PKCS#12
    /// into one error type so we can't usefully discriminate further.
    #[error("malformed P12 / wrong password for {path}: {cause}")]
    #[diagnostic(
        code(tynd::codesign::p12_parse),
        url("https://kvnpetit.github.io/tynd/docs/v1.0/guides/code-signing"),
        help(
            "either the file is not a valid PKCS#12, or the password from `identity.password_env` \
             is wrong. Re-export the .p12 from Keychain Access or `rcodesign \
             generate-self-signed-certificate`."
        )
    )]
    P12Parse { path: String, cause: String },

    #[error("target not found: {path}")]
    #[diagnostic(
        code(tynd::codesign::missing_target),
        url("https://kvnpetit.github.io/tynd/docs/v1.0/guides/code-signing"),
        help(
            "every entry in `targets` must be a built artifact — .app, .dmg, .pkg or Mach-O \
             binary. Run `tynd-bundler bundle` before `codesign`."
        )
    )]
    MissingTarget { path: String },

    #[error("signing rejected for {path}: {cause}")]
    #[diagnostic(
        code(tynd::codesign::sign_rejected),
        url("https://kvnpetit.github.io/tynd/docs/v1.0/guides/code-signing"),
        help(
            "apple-codesign refused the artifact. Common causes: the certificate does not have \
             the `Developer ID Application` extended key usage, the chain is incomplete, or the \
             artifact is not a recognized format."
        )
    )]
    SignRejected { path: String, cause: String },

    #[error("notarization for {path} timed out after {seconds}s (id={submission_id})")]
    #[diagnostic(
        code(tynd::codesign::notarize_timeout),
        url("https://kvnpetit.github.io/tynd/docs/v1.0/guides/code-signing"),
        help(
            "Apple's notary service can take >15 minutes under load. Resume with `rcodesign \
             notary-log <id>` once it finishes, then staple manually. Pass \
             `--allow-notarize-timeout` (or set `TYND_ALLOW_NOTARIZE_TIMEOUT=1`) if you intend to \
             staple later and want CI to keep going."
        )
    )]
    NotarizeTimeout {
        path: String,
        seconds: u64,
        submission_id: String,
    },

    #[error("notarization for {path} rejected: status = {status} (id={submission_id})")]
    #[diagnostic(
        code(tynd::codesign::notarize_rejected),
        url("https://kvnpetit.github.io/tynd/docs/v1.0/guides/code-signing"),
        help(
            "fetch the full diagnostic with `rcodesign notary-log <id>`. Typical causes: missing \
             hardened runtime, unsigned nested binary, or an entitlement Apple does not allow for \
             this distribution profile."
        )
    )]
    NotarizeRejected {
        path: String,
        status: String,
        submission_id: String,
    },
}

/// Per-invocation knobs that aren't part of the on-disk config, so they don't
/// belong on `CodesignConfig`. Today: a single opt-in escape hatch for
/// notarization timeouts. CLI sets these from `--allow-notarize-timeout` and
/// `TYND_ALLOW_NOTARIZE_TIMEOUT`.
#[derive(Debug, Default, Clone, Copy)]
pub(crate) struct RunOptions {
    /// When `true`, falling back from the strict `NotarizeTimeout` error to a
    /// `warn!` + `Ok(())` becomes the deliberate, opt-in behaviour for users
    /// who plan to staple later. Default is strict so CI fails loudly.
    pub allow_notarize_timeout: bool,
}

impl RunOptions {
    pub(crate) fn from_env() -> Self {
        let allow_notarize_timeout = std::env::var("TYND_ALLOW_NOTARIZE_TIMEOUT")
            .is_ok_and(|v| matches!(v.as_str(), "1" | "true" | "TRUE" | "yes" | "YES"));
        Self {
            allow_notarize_timeout,
        }
    }
}

pub(crate) fn run_with_options(cfg: &CodesignConfig, opts: RunOptions) -> Result<()> {
    let settings = build_settings(cfg)?;
    let signer = UnifiedSigner::new(settings);

    for target in &cfg.targets {
        sign_one(&signer, target).with_context(|| format!("sign {}", target.display()))?;
        // Echo the (re-)signed path so the caller can collect it.
        println!("{}", target.display());
    }

    if matches!(cfg.action, Action::Notarize) {
        let notar = cfg
            .notarization
            .as_ref()
            .ok_or_else(|| anyhow::Error::new(CodesignError::MissingAppleCredentials))?;
        let api_key_disp = notar.api_key_path.display().to_string();
        ensure_file_size(&notar.api_key_path, MAX_API_KEY_BYTES)
            .with_context(|| format!("validate App Store Connect API key {api_key_disp}"))?;
        let notarizer = Notarizer::from_api_key(&notar.api_key_path)
            .map_err(|e| Report::new(CodesignContext::LoadApiKey).attach(format!("source = {e:#}")))
            .attach_with({
                let p = api_key_disp.clone();
                move || format!("api_key_path = {p}")
            })
            .map_err(|report| {
                anyhow::Error::new(CodesignError::ApiKeyLoad {
                    path: api_key_disp.clone(),
                    cause: format!("{report:?}"),
                })
            })?;
        let stapler = Stapler::new().context("init stapler — Apple network reach required")?;
        for target in &cfg.targets {
            notarize_one(&notarizer, &stapler, target, opts)
                .with_context(|| format!("notarize {}", target.display()))?;
        }
    }
    Ok(())
}

/// `'static` lifetime works because the parsed P12 is `Box::leak`'d — this
/// binary runs once per invocation so the leak is bounded.
fn build_settings(cfg: &CodesignConfig) -> Result<SigningSettings<'static>> {
    let mut settings = match &cfg.identity {
        Identity::P12 { path, password_env } => p12_signing_settings(path, password_env)?,
    };

    // Required for notarization, harmless otherwise.
    settings.set_code_signature_flags(SettingsScope::Main, CodeSignatureFlags::RUNTIME);

    if let Some(ent) = &cfg.entitlements {
        let bytes = read_file_limited(ent, MAX_ENTITLEMENTS_BYTES)
            .with_context(|| format!("read entitlements {}", ent.display()))?;
        let xml = String::from_utf8(bytes)
            .with_context(|| format!("entitlements are not UTF-8: {}", ent.display()))?;
        settings
            .set_entitlements_xml(SettingsScope::Main, xml)
            .with_context(|| format!("apply entitlements {}", ent.display()))?;
    }

    Ok(settings)
}

/// Load the PKCS#12 keystore at `path` (passphrase from `password_env`) into
/// fresh signing settings.
fn p12_signing_settings(path: &Path, password_env: &str) -> Result<SigningSettings<'static>> {
    let pwd = std::env::var(password_env)
        .ok()
        .filter(|v| !v.is_empty())
        .ok_or_else(|| {
            anyhow::Error::new(CodesignError::MissingPasswordEnv {
                env_var: password_env.to_owned(),
            })
        })?;
    let p12_disp = path.display().to_string();
    let p12_context = |report: Report<CodesignContext>| {
        report
            .attach(format!("p12_path = {p12_disp}"))
            .attach(format!("password_env = {password_env}"))
    };
    // `std::io::Error` impls `StdError` so `Report::from` works directly.
    let bytes = read_file_limited(path, MAX_P12_BYTES)
        .map_err(Report::from)
        .change_context(CodesignContext::LoadP12)
        .map_err(p12_context)
        .map_err(|report| {
            anyhow::Error::new(CodesignError::P12Read {
                path: p12_disp.clone(),
                cause: format!("{report:?}"),
            })
        })?;
    // `parse_pfx_data` returns `apple_codesign::AppleCodesignError`,
    // which is a `thiserror`-derived enum that does impl `StdError`.
    let (cert, key) = parse_pfx_data(&bytes, &pwd)
        .map_err(Report::from)
        .change_context(CodesignContext::LoadP12)
        .map_err(p12_context)
        .attach_with({
            let n = bytes.len();
            move || format!("p12_size_bytes = {n}")
        })
        .map_err(|report| {
            // Defensively scrub the password (never empty, see above) from
            // the rendered chain.
            let cause = format!("{report:?}").replace(&pwd, "***REDACTED***");
            anyhow::Error::new(CodesignError::P12Parse {
                path: p12_disp.clone(),
                cause,
            })
        })?;

    // The signing key must outlive `SigningSettings<'key>`. Single-shot CLI,
    // so leaking into 'static is bounded — OS reclaims on process exit.
    let key_box: Box<dyn PrivateKey> = Box::new(key);
    let key_static: &'static dyn PrivateKey = Box::leak(key_box);

    let mut settings = SigningSettings::default();
    settings.set_signing_key(key_static, cert);
    Ok(settings)
}

fn ensure_file_size(path: &Path, max_bytes: u64) -> std::io::Result<()> {
    let size = std::fs::metadata(path)?.len();
    if size > max_bytes {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            format!(
                "{} is {size} bytes; maximum allowed size is {max_bytes} bytes",
                path.display()
            ),
        ));
    }
    Ok(())
}

fn read_file_limited(path: &Path, max_bytes: u64) -> std::io::Result<Vec<u8>> {
    let file = std::fs::File::open(path)?;
    let size = file.metadata()?.len();
    if size > max_bytes {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            format!(
                "{} is {size} bytes; maximum allowed size is {max_bytes} bytes",
                path.display()
            ),
        ));
    }
    let mut bytes = Vec::with_capacity(size as usize);
    file.take(max_bytes + 1).read_to_end(&mut bytes)?;
    if bytes.len() as u64 > max_bytes {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            format!(
                "{} grew beyond {max_bytes} bytes while reading",
                path.display()
            ),
        ));
    }
    Ok(bytes)
}

fn sign_one(signer: &UnifiedSigner<'_>, target: &Path) -> Result<()> {
    if !target.exists() {
        return Err(anyhow::Error::new(CodesignError::MissingTarget {
            path: target.display().to_string(),
        }));
    }
    info!("sign: {}", target.display());
    let target_disp = target.display().to_string();
    let target_kind = target
        .extension()
        .and_then(|e| e.to_str())
        .unwrap_or("<no-ext>");
    signer
        .sign_path_in_place(target)
        .map_err(|e| Report::new(CodesignContext::SignArtifact).attach(format!("source = {e:#}")))
        .attach_with({
            let p = target_disp.clone();
            move || format!("target = {p}")
        })
        .attach_with({
            let k = target_kind.to_string();
            move || format!("target_kind = {k}")
        })
        .map_err(|report| {
            anyhow::Error::new(CodesignError::SignRejected {
                path: target_disp.clone(),
                cause: format!("{report:?}"),
            })
        })?;
    Ok(())
}

fn notarize_one(
    notarizer: &Notarizer,
    stapler: &Stapler,
    target: &Path,
    opts: RunOptions,
) -> Result<()> {
    info!("notarize: {}", target.display());
    let target_disp = target.display().to_string();
    let outcome = notarizer
        .notarize_path(target, Some(NOTARIZE_WAIT))
        .map_err(|e| Report::new(CodesignContext::NotarizeSubmit).attach(format!("source = {e:#}")))
        .attach_with({
            let p = target_disp.clone();
            move || format!("target = {p}")
        })
        .attach_with(|| format!("wait_secs = {}", NOTARIZE_WAIT.as_secs()))
        .map_err(|report| anyhow::anyhow!("{report:?}"))
        .with_context(|| format!("notarize submit {target_disp}"))?;
    match outcome {
        NotarizationUpload::UploadId(id) => {
            // Strict default: returning `Ok(())` here was misleading CI into
            // shipping un-notarized artifacts as "successful". Surface the
            // timeout as a typed error unless the caller explicitly opted in.
            if opts.allow_notarize_timeout {
                warn!(
                    "notarize {}: did not wait for completion — submission id={id}. Check \
                     `rcodesign notary-log {id}` later, then run staple manually. \
                     (TYND_ALLOW_NOTARIZE_TIMEOUT / --allow-notarize-timeout is set.)",
                    target.display()
                );
                return Ok(());
            }
            return Err(anyhow::Error::new(CodesignError::NotarizeTimeout {
                path: target_disp,
                seconds: NOTARIZE_WAIT.as_secs(),
                submission_id: id,
            }));
        },
        NotarizationUpload::NotaryResponse(resp) => {
            // Staple only on Accepted; otherwise surface the submission ID
            // so the user can run `rcodesign notary-log <id>`.
            if !matches!(
                resp.data.attributes.status,
                SubmissionResponseStatus::Accepted
            ) {
                return Err(anyhow::Error::new(CodesignError::NotarizeRejected {
                    path: target_disp,
                    status: resp.data.attributes.status.to_string(),
                    submission_id: resp.data.id,
                }));
            }
        },
    }
    stapler
        .staple_path(target)
        .map_err(|e| Report::new(CodesignContext::StapleArtifact).attach(format!("source = {e:#}")))
        .attach_with({
            let p = target_disp.clone();
            move || format!("target = {p}")
        })
        .map_err(|report| anyhow::anyhow!("{report:?}"))
        .with_context(|| format!("staple {target_disp}"))?;
    info!("notarize+staple ok: {}", target.display());
    Ok(())
}
