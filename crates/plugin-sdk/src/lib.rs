/// Internal plumbing for the `#[plugin_impl]` proc macro. Not part of the
/// stable SDK surface.
#[doc(hidden)]
pub mod __internal {
    use serde::Serialize;
    use serde_json::Value;

    use super::{PluginError, PluginResult};

    /// Normalises a plugin command's return value into a
    /// `PluginResult<Value>` for the dispatch boundary. The
    /// `#[plugin_impl]` proc-macro emits a call to this trait so
    /// commands written as `fn foo(..) -> PluginResult<T>` and bare
    /// `fn foo(..) -> T` both flatten to the wire `Value`. Plugin
    /// authors do not implement it — only the SDK-internal blanket
    /// impl ships, and the macro stitches it in for you.
    ///
    /// ```ignore
    /// // Generated by `#[plugin_impl]` for every command:
    /// let __out = self.greet(args);
    /// ::tynd_plugin_sdk::__internal::IntoValueRoute::into_value_route(__out)
    /// ```
    ///
    /// Canonical implementor: `impl<T: Serialize> IntoValueRoute for
    /// PluginResult<T>` below — the only impl in the codebase.
    pub trait IntoValueRoute {
        /// Serialise the wrapped success value to JSON, or propagate
        /// the inner error.
        fn into_value_route(self) -> PluginResult<Value>;
    }

    impl<T: Serialize> IntoValueRoute for PluginResult<T> {
        fn into_value_route(self) -> PluginResult<Value> {
            self.and_then(|v| {
                serde_json::to_value(v)
                    .map_err(|e| PluginError::Custom(format!("serialise return: {e}")))
            })
        }
    }

    /// Synchronous executor with **NO tokio runtime**.
    ///
    /// # WARNING
    ///
    /// This blocks on a future via `pollster::block_on` — there is no
    /// reactor, no I/O driver, no timer wheel. Plugin async fn bodies
    /// must NOT call `tokio::*` APIs (`tokio::spawn`, `tokio::time::sleep`,
    /// `tokio::fs`, `tokio::net`, …) — they panic at runtime with
    /// `there is no reactor running, must be called from the context of a Tokio runtime`.
    ///
    /// Use `std::thread::spawn` + [`BackgroundHandle`](crate::BackgroundHandle)
    /// or wrap blocking I/O in plain sync functions. If tokio interop is
    /// genuinely needed, the host owns a runtime; route through the SDK's
    /// IPC, not directly.
    pub fn block_on<F: std::future::Future>(fut: F) -> F::Output {
        ::pollster::block_on(fut)
    }
}

/// Register the plugin constructor for the host-generated `main.rs`.
/// Expands to `pub fn __tynd_plugin() -> Arc<dyn TyndPlugin>`.
///
/// **Mutually exclusive with `#[plugin]` macro — choose one.** Combining
/// both produces a duplicate-symbol compile error because `#[plugin]`
/// already emits the same `__tynd_plugin` constructor under the hood.
#[macro_export]
macro_rules! register_plugin {
    ($ctor:expr) => {
        #[doc(hidden)]
        pub fn __tynd_plugin() -> ::std::sync::Arc<dyn $crate::TyndPlugin> {
            ::std::sync::Arc::new($ctor)
        }
    };
}
