//! `tynd-plugin-sdk` — the contract between the Tynd host and third-party
//! native plugins.
//!
//! A native plugin implements [`TyndPlugin`], ships its Rust sources in its
//! npm package under `native/`, and is picked up at build time by
//! `tynd build`. At runtime the host's plugin dispatcher looks up the
//! plugin by `name()` and delegates each IPC call to [`TyndPlugin::dispatch`].
//!
//! Deliberately small surface: no trait objects for events, no ABI
//! versioning (plugins + host compile together), JSON values over serde.

