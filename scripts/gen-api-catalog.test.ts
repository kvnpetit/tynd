import { describe, expect, test } from "bun:test";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import {
  type ApiEntry,
  checkPlugins,
  checkSchemaApis,
  parseAddNames,
  parseCatalog,
  readAddNames,
  readHostPlugins,
  readPublishedSchema,
  renderConfigTypes,
  renderRust,
  type SchemaNode,
  spliceCargo,
  targets,
  tsType,
} from "./gen-api-catalog";

const ROOT = path.resolve(import.meta.dir, "..");

const manifest = (apis: string[], features: string[]) => `
[package.metadata.tynd.apis]
${apis.join("\n")}

[features]
${features.map((feature) => `${feature} = []`).join("\n")}
`;

const SAMPLE = manifest(
  [
    'zeta = { plugin = "@tynd/plugin-zeta" }',
    "alpha = { core = true }",
    "beta-two = { core = true }",
    "plain = {}",
  ],
  ["api-all", "api-zeta", "api-plain", "obs-otel"],
);

describe("parseCatalog", () => {
  test("sorts by name and derives the feature", () => {
    const entries = parseCatalog(SAMPLE);
    expect(entries.map((entry) => entry.name)).toEqual(["alpha", "beta-two", "plain", "zeta"]);
    expect(entries.find((entry) => entry.name === "plain")?.feature).toBe("api-plain");
    expect(entries.find((entry) => entry.name === "beta-two")?.feature).toBeUndefined();
    expect(entries.find((entry) => entry.name === "zeta")?.plugin).toBe("@tynd/plugin-zeta");
  });

  test("is independent of manifest order", () => {
    const reversed = manifest(
      [
        "plain = {}",
        "beta-two = { core = true }",
        "alpha = { core = true }",
        'zeta = { plugin = "@tynd/plugin-zeta" }',
      ],
      ["obs-otel", "api-plain", "api-zeta", "api-all"],
    );
    expect(parseCatalog(reversed)).toEqual(parseCatalog(SAMPLE));
  });

  test("rejects a missing cargo feature", () => {
    expect(() => parseCatalog(manifest(["ghost = {}"], ["api-all"]))).toThrow(/api-ghost/);
  });

  test("rejects a core api that still has a cargo feature", () => {
    expect(() => parseCatalog(manifest(["a = { core = true }"], ["api-a"]))).toThrow(
      /core and must not have cargo feature "api-a"/,
    );
  });

  test("rejects an api feature missing from the catalog", () => {
    expect(() => parseCatalog(manifest(["a = {}"], ["api-a", "api-b"]))).toThrow(/api-b/);
  });

  test("rejects unknown keys and conflicting flags", () => {
    expect(() => parseCatalog(manifest(["a = { nope = 1 }"], ["api-a"]))).toThrow(/unknown key/);
    expect(() => parseCatalog(manifest(['a = { core = true, plugin = "@x/y" }'], []))).toThrow(
      /both core and plugin-first/,
    );
  });
});

describe("renderers are deterministic", () => {
  const entries = parseCatalog(SAMPLE);

  test("rust", () => {
    expect(renderRust(entries)).toBe(renderRust([...entries].reverse().sort(sortByName)));
    // Short lists stay on one line and long ones wrap, exactly like `cargo fmt`.
    expect(renderRust(entries)).toContain(
      'pub(crate) const CORE_HOST_APIS: &[&str] = &["alpha", "beta-two"];',
    );
    expect(renderRust(entries)).toContain('pub(crate) const KNOWN_APIS: &[&str] = &["alpha", ');
    const names = ["one", "two", "three", "four", "five", "six", "seven", "eight"];
    const many = parseCatalog(
      manifest(
        names.map((name) => `${name}-long-api = { core = true }`),
        ["api-all"],
      ),
    );
    expect(renderRust(many)).toContain(
      'pub(crate) const CORE_HOST_APIS: &[&str] = &[\n    "eight-long-api",',
    );
    expect(renderRust(entries)).toContain('("zeta", "@tynd/plugin-zeta"),');
  });

  test("cargo lists keep the rest of the file", () => {
    const source = `a = 1\n# keep\napi-all = [ "y" ]\nz = 2\n`;
    const output = spliceCargo(source, entries);
    // Core APIs have no feature, so they stay out of `api-all`.
    expect(output).toContain('api-all = [\n    "api-plain",\n    "api-zeta",\n]\nz = 2');
    expect(output).not.toContain("api-alpha");
    expect(output).toContain("# keep");
    expect(spliceCargo(output, entries)).toBe(output);
  });

  test("rust is a whole generated file", () => {
    const output = renderRust(entries);
    expect(output.startsWith("// @generated by scripts/gen-api-catalog.ts")).toBe(true);
    expect(output.endsWith("];\n")).toBe(true);
  });
});

function sortByName(left: ApiEntry, right: ApiEntry): number {
  return left.name < right.name ? -1 : 1;
}

describe("parseAddNames", () => {
  const entries = parseCatalog(SAMPLE);
  const plugin = (id: string, aliases: string[], extra: Record<string, unknown> = {}) => ({
    id,
    kind: "standalone",
    pkg: `@tynd/plugin-${id}`,
    aliases,
    apis: [],
    ...extra,
  });
  const parse = (plugins: unknown[]) => parseAddNames(JSON.stringify(plugins), entries);

  test("maps ids and aliases to the package and the fronted api", () => {
    const names = parse([
      plugin("zeta", ["zed"], { kind: "host", apis: ["zeta"] }),
      plugin("db-tool", ["db"]),
    ]);
    expect(names).toEqual([
      { name: "db", package: "@tynd/plugin-db-tool" },
      { name: "db-tool", package: "@tynd/plugin-db-tool" },
      { name: "zed", package: "@tynd/plugin-zeta", api: "zeta" },
      { name: "zeta", package: "@tynd/plugin-zeta", api: "zeta" },
    ]);
    const output = renderRust(entries, names);
    expect(output).toContain('    ("zed", "@tynd/plugin-zeta", Some("zeta")),');
    expect(output).toContain('    ("db", "@tynd/plugin-db-tool", None),');
  });

  test("carries the dist-tag of a plugin published under one", () => {
    const names = parse([plugin("beta-tool", ["bt"], { distTag: "experimental" })]);
    expect(names).toEqual([
      { name: "beta-tool", package: "@tynd/plugin-beta-tool", distTag: "experimental" },
      { name: "bt", package: "@tynd/plugin-beta-tool", distTag: "experimental" },
    ]);
    expect(renderRust(entries, names)).toContain(
      'pub(crate) const PLUGIN_DIST_TAGS: &[(&str, &str)] = &[\n    ("@tynd/plugin-beta-tool", "experimental"),\n];',
    );
    expect(renderRust(entries, [])).toContain(
      "pub(crate) const PLUGIN_DIST_TAGS: &[(&str, &str)] = &[];",
    );
    expect(() => parse([plugin("one", [], { distTag: "latest" })])).toThrow(/distTag/);
    expect(() => parse([plugin("one", [], { distTag: 1 })])).toThrow(/distTag/);
  });

  test("rejects alias collisions", () => {
    expect(() => parse([plugin("one", ["shared"]), plugin("two", ["shared"])])).toThrow(
      /"shared" is claimed by both "one" and "two"/,
    );
    expect(() => parse([plugin("one", []), plugin("two", ["one"])])).toThrow(/claimed by both/);
    expect(() => parse([plugin("one", ["alpha"])])).toThrow(/shadows the "alpha" host api/);
  });

  test("rejects a host-backed plugin that does not front its api", () => {
    expect(() => parse([plugin("plain", [], { kind: "host", apis: ["plain"] })])).toThrow(
      /not fronted by/,
    );
  });
});

describe("checkPlugins", () => {
  const entries = parseCatalog(SAMPLE);
  test("accepts a consistent set", () => {
    expect(checkPlugins(entries, [{ name: "@tynd/plugin-zeta", apis: ["zeta"] }])).toEqual([]);
  });
  test("reports missing and mismatched packages", () => {
    expect(checkPlugins(entries, [])).toHaveLength(1);
    const issues = checkPlugins(entries, [{ name: "@tynd/plugin-other", apis: ["alpha"] }]);
    expect(issues.some((issue) => issue.includes("alpha"))).toBe(true);
  });
});

describe("repository", () => {
  const entries = parseCatalog(readFileSync(path.join(ROOT, "crates/host/Cargo.toml"), "utf8"));

  test("keeps the core minimal, fronts UI APIs with plugins and excludes debug-screenshot", () => {
    const core = entries.filter((entry) => entry.core).map((entry) => entry.name);
    expect(core).toEqual(["acl", "log"]);
    for (const name of ["menu", "tray", "multiwindow"]) {
      expect(entries.find((entry) => entry.name === name)?.plugin).toBe(`@tynd/plugin-${name}`);
    }
    expect(entries.some((entry) => entry.name === "debug-screenshot")).toBe(false);
  });

  test("plugins/catalog.json names are unique and resolvable", () => {
    const names = readAddNames(ROOT, entries);
    expect(names.find((item) => item.name === "kv")).toEqual({
      name: "kv",
      package: "@tynd/plugin-store",
      api: "store",
    });
    expect(names.find((item) => item.name === "db")?.package).toBe("@tynd/plugin-sql");
  });

  test("host-backed plugins agree with the catalog", () => {
    expect(checkPlugins(entries, readHostPlugins(ROOT))).toEqual([]);
  });

  test("every generated file is fresh", () => {
    for (const target of targets(ROOT, entries)) {
      const file = path.join(ROOT, target.file);
      expect(existsSync(file)).toBe(true);
      const current = readFileSync(file, "utf8");
      expect({ file: target.file, fresh: target.render(current) === current }).toEqual({
        file: target.file,
        fresh: true,
      });
    }
  });
});

describe("config types", () => {
  test("maps schema shapes to TypeScript", () => {
    expect(tsType({ type: "string", minLength: 1 } as SchemaNode)).toBe("string");
    expect(tsType({ $ref: "#/$defs/ApiName" })).toBe("ApiName");
    expect(tsType({ const: true, type: "boolean" })).toBe("true");
    expect(tsType({ type: "string", enum: ["a", "b"] })).toBe('"a" | "b"');
    expect(tsType({ type: "array", items: { type: "string" } })).toBe("string[]");
    expect(tsType({ type: "array", items: { type: "string" }, minItems: 1 })).toBe(
      "[string, ...string[]]",
    );
    expect(
      tsType({ type: "array", items: { anyOf: [{ type: "string" }, { type: "integer" }] } }),
    ).toBe("(string | number)[]");
    expect(tsType({ type: "object", additionalProperties: { type: "string" } })).toBe(
      "Record<string, string>",
    );
  });

  test("renders required and optional members with their docs", () => {
    const output = renderConfigTypes({
      type: "object",
      description: "Root.",
      properties: {
        name: { type: "string", description: "Display name.", default: "app" },
        "odd-key": { type: "boolean" },
      },
      required: ["name"],
      $defs: { Mode: { type: "string", enum: ["on", "off"] } },
    });
    expect(output).toContain("/** Root. */\nexport interface TyndConfig {");
    expect(output).toContain(
      '  /**\n   * Display name.\n   * @default "app"\n   */\n  name: string;',
    );
    expect(output).toContain('  "odd-key"?: boolean;');
    expect(output).toContain('export type Mode = "on" | "off";');
  });

  test("rejects schema keywords it cannot express", () => {
    expect(() => tsType({ allOf: [] } as SchemaNode)).toThrow(/unsupported keyword "allOf"/);
  });

  test("the published schema lists exactly the catalog APIs", () => {
    const entries = parseCatalog(readFileSync(path.join(ROOT, "crates/host/Cargo.toml"), "utf8"));
    const schema = readPublishedSchema(ROOT);
    expect(() => checkSchemaApis(schema, entries)).not.toThrow();
    expect(() => checkSchemaApis(schema, entries.slice(1))).toThrow(/ApiName list differs/);
  });
});
