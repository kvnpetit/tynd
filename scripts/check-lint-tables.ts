// Every Cargo workspace and standalone crate in the repo must carry the root
// `[workspace.lints]` table, either through `[lints] workspace = true` or as
// an identical copy where the crate ships on its own (the generated
// @tynd/plugin-sdk and @tynd/host-src mirrors).
//
// Usage: bun scripts/check-lint-tables.ts
import { existsSync } from "node:fs";
import { join } from "node:path";

type Table = Record<string, unknown>;

const ROOT = join(import.meta.dir, "..");

function isTable(value: unknown): value is Table {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function canonical(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonical);
  if (!isTable(value)) return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, canonical(value[key])]),
  );
}

async function readToml(relPath: string): Promise<Table> {
  const parsed: unknown = Bun.TOML.parse(await Bun.file(join(ROOT, relPath)).text());
  if (!isTable(parsed)) throw new Error(`${relPath}: not a TOML table`);
  return parsed;
}

function pick(doc: Table, path: readonly string[]): unknown {
  let node: unknown = doc;
  for (const key of path) {
    if (!isTable(node)) return undefined;
    node = node[key];
  }
  return node;
}

function diffKeys(expected: Table, actual: Table): string[] {
  const out: string[] = [];
  for (const group of new Set([...Object.keys(expected), ...Object.keys(actual)])) {
    const want = isTable(expected[group]) ? expected[group] : {};
    const got = isTable(actual[group]) ? actual[group] : {};
    for (const lint of new Set([...Object.keys(want), ...Object.keys(got)])) {
      const a = JSON.stringify(canonical(want[lint]));
      const b = JSON.stringify(canonical(got[lint]));
      if (a !== b)
        out.push(`${group}.${lint}: expected ${a ?? "(absent)"}, found ${b ?? "(absent)"}`);
    }
  }
  return out;
}

const rootDoc = await readToml("Cargo.toml");
const reference = pick(rootDoc, ["workspace", "lints"]);
if (!isTable(reference)) throw new Error("Cargo.toml: missing [workspace.lints]");

const copies: { file: string; path: readonly string[]; optional?: boolean }[] = [
  // Generated by `bun run --cwd packages/plugin-sdk sync`; absent in a fresh checkout.
  { file: "packages/plugin-sdk/native/Cargo.toml", path: ["lints"], optional: true },
  { file: "packages/plugin-sdk/native-macros/Cargo.toml", path: ["lints"], optional: true },
  // Generated by `bun run sync:host-src`; absent in a fresh checkout.
  { file: "packages/host-src/native/Cargo.toml", path: ["workspace", "lints"], optional: true },
];

const problems: string[] = [];

for (const copy of copies) {
  if (copy.optional && !existsSync(join(ROOT, copy.file))) continue;
  const table = pick(await readToml(copy.file), copy.path);
  if (!isTable(table)) {
    problems.push(`${copy.file}: missing [${copy.path.join(".")}]`);
    continue;
  }
  for (const line of diffKeys(reference, table)) problems.push(`${copy.file}: ${line}`);
}

/** Every crate of a workspace's `members` (minus `skip`) must declare `[lints] workspace = true`. */
async function checkMembersInherit(
  manifest: string,
  skip: ReadonlySet<string> = new Set(),
): Promise<void> {
  const dir = manifest.replace(/\/?Cargo\.toml$/, "");
  const members = pick(await readToml(manifest), ["workspace", "members"]);
  for (const member of Array.isArray(members) ? members : []) {
    if (typeof member !== "string" || skip.has(member)) continue;
    const file = dir ? `${dir}/${member}/Cargo.toml` : `${member}/Cargo.toml`;
    const lints = pick(await readToml(file), ["lints"]);
    if (!isTable(lints) || lints.workspace !== true) {
      problems.push(`${file}: expected [lints] workspace = true`);
    }
  }
}

const standalone = new Set(copies.map((c) => c.file.replace(/\/Cargo\.toml$/, "")));
await checkMembersInherit("Cargo.toml", standalone);

if (problems.length > 0) {
  process.stderr.write("Lint tables drifted from the root [workspace.lints]:\n");
  for (const p of problems) process.stderr.write(`  ${p}\n`);
  process.exit(1);
}
process.stdout.write("Lint tables match the root [workspace.lints].\n");
